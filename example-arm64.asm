/* ======================================================
   ARM64 AArch64 全集语法演示
   适用：Linux ARM64、裸机、QEMU 可直接运行
   汇编器：GNU as
====================================================== */

// ===================== 1. 汇编伪指令 & 全局符号 & 常量定义 =====================
.global _start          // 程序入口全局导出
.global func_demo      // 导出自定义函数
.align 3               // 8字节对齐(ARM64推荐)
.equ    CONST_VAL, 0x12345678
.equ    STACK_TOP,  0x80000000

// 自定义宏语法
.macro  ADD3 op1,op2,op3
        ADD \op1, \op2, \op3
.endm

// ===================== 2. 数据段定义 =====================
.section .data
// 字符串、字节、半字、字、双字
str_buf:    .asciz  "ARM64 AArch64 All Assembly Syntax\n"
byte_arr:   .byte   0x01,0x02,0x03,0x04
half_arr:   .hword  0x1122,0x3344,0x5566
word_arr:   .word   0x20000000,0x30000000
quad_arr:   .xword  0x123456789ABCDEF0

// ===================== 3. 代码段 =====================
.section .text

_start:
        // --------------------------
        // 3.1 ARM64 寄存器基础使用
        // X0~X31 64位通用寄存器
        // W0~W31 32位窄寄存器
        // SP 栈指针、PC 程序计数器、LR(X30)链接寄存器
        // --------------------------
        MOV     X0, #0
        MOV     W1, #0x10
        MOV     X2, #CONST_VAL

        // 寄存器间传送
        MOV     X3, X2

        // --------------------------
        // 3.2 算术运算指令
        // ADD SUB ADC SBC MUL MADD MSUB
        // --------------------------
        ADD     X4, X0, X1
        ADD     X5, X2, #0x1000     // 寄存器+立即数
        SUB     X6, X5, X3
        ADC     X7, X0, X1          // 带进位加法
        SBC     X8, X5, X3          // 带借位减法

        MUL     X9, X1, X2          // 64位乘法
        MADD    X10,X1,X2,X3        // 乘累加 X10 = X1*X2 + X3

        // --------------------------
        // 3.3 位运算 & 逻辑指令
        // AND ORR EOR BIC ORN EON
        // --------------------------
        AND     X11,X2,#0xFF
        ORR     X12,X1,#0x0F
        EOR     X13,X2,X3
        BIC     X14,X2,#0xF000

        // --------------------------
        // 3.4 移位指令 全部移位语法
        // LSL LSR ASR ROR
        // --------------------------
        LSL     X0, X2, #3
        LSR     X1, X2, #4
        ASR     X2, X3, #2
        ROR     X3, X4, #1

        // --------------------------
        // 3.5 比较 & 条件标志 & 条件选择
        // CMP CMN TST CCMP CSEL
        // --------------------------
        CMP     X0, X1
        CMN     X2, X3
        TST     X4, #0xFF

        // 条件选择（ARM64 常用替代条件执行）
        CSEL    X5, X0, X1, EQ
        CSEL    X6, X2, X3, GT

        // --------------------------
        // 3.6 内存加载存储 + 全部寻址方式
        // 基址偏移、前变址、后变址、寄存器偏移
        // LDR STR LDRB STRB LDRH STRH LDRSW
        // --------------------------
        ADRP    X15, _start         // 页级相对寻址
        ADR     X16, str_buf        // 小范围相对寻址

        LDR     X17, [X16]          // 基址寻址 加载双字
        LDR     W18, [X16]          // 加载32位字
        LDRB    W19, [X16]          // 加载字节
        LDRH    W20, [X16]          // 加载半字
        LDRSW   X21, [X16]          // 加载带符号字扩展64位

        STR     X17, [X16, #8]      // 基址+立即偏移
        STR     X18, [X16, X5]      // 寄存器偏移寻址
        STR     X19, [X16, #16]!    // 前变址 回写基址
        STRH    W20, [X16], #2      // 后变址 先存取再偏移

        // --------------------------
        // 3.7 多寄存器访存 / 批量加载存储
        // LDP STP 成对读写（ARM64主流）
        // --------------------------
        STP     X0, X1, [SP, #-16]!
        LDP     X0, X1, [SP], #16

        // --------------------------
        // 3.8 跳转 & 函数调用指令
        // B BL BRL JUMP RET
        // --------------------------
        B       label_jump          // 无条件跳转
label_jump:
        BL      func_demo           // 调用函数，保存返回地址到 X30(LR)
        RET                         // 函数返回 = B LR

        // --------------------------
        // 3.9 栈操作 标准ARM64栈用法
        // --------------------------
        MOV     SP, #STACK_TOP
        STP     X29, X30, [SP, #-16]!  // 保存帧指针+链接寄存器
        LDP     X29, X30, [SP], #16    // 恢复

        // --------------------------
        // 3.10 自定义宏调用
        // --------------------------
        MOV     W0, #50
        MOV     W1, #30
        ADD3    W2, W0, W1

        // --------------------------
        // 3.11 简单循环结构
        // --------------------------
        MOV     W22, #0
loop_start:
        ADD     W22, W22, #1
        CMP     W22, #5
        B.LT    loop_start

        // --------------------------
        // 死循环收尾
        // --------------------------
end_loop:
        B       end_loop

// ===================== 4. 自定义函数定义 =====================
func_demo:
        SUB     SP, SP, #16
        STP     X0, X1, [SP]

        MOV     X0, #0xAAAA
        MOV     X1, #0x5555

        LDP     X0, X1, [SP]
        ADD     SP, SP, #16
        RET
