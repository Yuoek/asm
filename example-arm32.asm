
@ ==============================================
@ ARM32 汇编全覆盖语法示例 GNU 汇编格式
@ 适用：ARMv7-A 裸机 / Linux ARM 汇编
@ ==============================================

@ 1. 全局声明、程序入口、伪指令
.global _start        @ 全局入口符号
.global func_test     @ 导出函数
.align 4              @ 4字节对齐
.equ  VAL, 0x1234     @ 定义常量 VAL = 0x1234
.equ  STACK_BASE, 0x80001000  @ 栈基地址

@ 2. 宏定义语法
.macro  ADD_2REG r1, r2
        ADD \r1, \r1, \r2
.endm

@ 3. 数据段定义
.section .data
str:    .asciz  "ARM Assembly All Syntax!\n"  @ 以0结尾字符串
buf:    .byte   1,2,3,4                     @ 字节数组
num:    .word   0x2000, 0x3000              @ 字数组(4字节)
arr:    .hword  0x1122, 0x3344              @ 半字数组(2字节)

@ 4. 代码段
.section .text
_start:
        @ --------------------------
        @ 4.1 寄存器基础操作
        @ 通用寄存器 R0~R15, CPSR 状态寄存器
        @ --------------------------
        MOV     R0, #0          @ 立即数寻址：R0 = 0
        MOV     R1, #VAL        @ 使用.equ 常量
        LDR     R2, =num        @ 加载标签地址到R2

        @ --------------------------
        @ 4.2 算术运算指令
        @ ADD SUB MUL MLA RSB ADC SBC
        @ --------------------------
        ADD     R3, R0, R1      @ R3 = R0 + R1
        ADD     R3, R1, #0x10   @ 寄存器+立即数
        SUB     R4, R1, R3      @ 减法
        RSB     R5, R1, #0x5000 @ 反向减法 R5 = 0x5000 - R1
        ADC     R6, R0, R0      @ 带进位加法
        SBC     R7, R1, R3      @ 带借位减法

        @ 乘法指令
        MUL     R8, R1, R2      @ 32位乘法 R8 = R1 * R2

        @ --------------------------
        @ 4.3 位运算指令
        @ AND ORR EOR BIC LSL LSR ASR ROR
        @ --------------------------
        AND     R9, R1, #0xFF
        ORR     R10,R1, #0x0F
        EOR     R11,R1, #0x55
        BIC     R12,R1, #0xF0

        LSL     R0, R1, #2      @ 逻辑左移 <<2
        LSR     R1, R0, #1      @ 逻辑右移 >>1
        ASR     R2, R1, #1      @ 算术右移（保留符号）
        ROR     R3, R1, #2      @ 循环右移

        @ --------------------------
        @ 4.4 内存加载存储 + 各种寻址方式
        @ 立即寻址、寄存器寻址、基址偏移、前变址、后变址
        @ LDR STR LDRB STRB LDRH STRH
        @ --------------------------
        LDR     R4, [R2]        @ 基址寻址：取字
        LDRB    R5, [R2]        @ 取字节
        LDRH    R6, [R2]        @ 取半字

        STR     R5, [R2, #4]    @ 基址+偏移
        STR     R6, [R2, R3]    @ 寄存器偏移寻址
        STR     R7, [R2, #8]!   @ 前变址 写回基址
        STRB    R8, [R2], #1    @ 后变址 先存取再偏移

        @ --------------------------
        @ 4.5 条件执行指令（ARM 特色）
        @ EQ NE CS CC MI PL VS VC HI LS GE LT GT LE AL
        @ --------------------------
        CMP     R1, R2          @ 比较，更新CPSR标志
        MOVEQ   R0, #1          @ 相等则执行MOV
        MOVNE   R0, #2          @ 不等则执行MOV
        MOVGT   R1, #0x10
        MOVLT   R2, #0x20

        @ --------------------------
        @ 4.6 跳转指令
        @ B BL BX BLX
        @ --------------------------
        B       jump_label      @ 无条件跳转
jump_label:
        BL      func_test       @ 带链接跳转(调用函数，保存返回地址到LR)
        BX      LR              @ 跳回LR，函数返回

        @ --------------------------
        @ 4.7 栈操作指令
        @ STMFD LDMFD 满递减栈
        @ --------------------------
        LDR     SP, =STACK_BASE @ 设置栈指针
        STMFD   SP!, {R0-R12, LR}  @ 压栈保存寄存器
        LDMFD   SP!, {R0-R12, PC}  @ 出栈恢复并跳转

        @ --------------------------
        @ 4.8 伪指令、地址加载
        @ --------------------------
        LDR     R0, =str        @ 加载字符串地址
        ADR     R1, _start      @ 相对小范围地址加载

        @ --------------------------
        @ 4.9 宏调用语法
        @ --------------------------
        MOV     R0, #10
        MOV     R1, #20
        ADD_2REG R0, R1         @ 调用自定义宏

        @ --------------------------
        @ 4.10 函数定义示例
        @ --------------------------
func_test:
        MOV     R0, #0x88
        MOV     PC, LR          @ 函数返回

        @ --------------------------
        @ 4.11 死循环收尾
        @ --------------------------
loop:
        B       loop
